-- Формулировка: Более опытные агенты закрывают больше сделок.
--
-- Вывод: не наблюдается чёткой зависимости между опытом агента
-- и количеством совершённых сделок. Агенты с разным уровнем опыта
-- показывают как высокие, так и низкие результаты. Это может
-- означать, что эффективность агента зависит не только от опыта,
-- но и от других факторов (активность, количество объявлений,
-- качество объектов).

SELECT
    a.experience_years,
    a.full_name,
    count(d.deal_id) AS total_deals
FROM agents a
LEFT JOIN listings l ON a.agent_id = l.agent_id
LEFT JOIN deals d ON l.listing_id = d.listing_id
GROUP BY a.experience_years, a.full_name
ORDER BY a.experience_years DESC;
