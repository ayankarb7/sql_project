-- Формулировка: Часть клиентов активно просматривает объекты,
-- но не совершает сделки.
--
-- Вывод: существует группа клиентов с высоким количеством
-- просмотров, но без совершённых сделок. Это может говорить
-- о том, что часть пользователей проявляет интерес к объектам,
-- но не переходит к покупке. Возможные причины: высокая цена,
-- несоответствие ожиданиям или длительный процесс принятия решения.

SELECT
    c.client_id,
    c.full_name,
    count(DISTINCT v.viewing_id) AS total_views,
    count(DISTINCT d.deal_id) AS total_deals
FROM clients c
LEFT JOIN viewings v ON c.client_id = v.client_id
LEFT JOIN deals d ON c.client_id = d.buyer_id
GROUP BY c.client_id, c.full_name
ORDER BY total_views DESC;
