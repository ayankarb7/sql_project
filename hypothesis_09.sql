-- Формулировка: В некоторых районах находится значительно больше
-- объектов недвижимости, чем в других.
--
-- Вывод: количество объектов распределено по районам неравномерно,
-- но сильного контраста в цифрах не замечается. Некоторые районы
-- представлены значительно большим числом объектов, что может
-- говорить о более активном рынке недвижимости в этих локациях.

SELECT
    district,
    count(*) AS total_properties
FROM properties
GROUP BY district
HAVING count(*) > 20
ORDER BY total_properties DESC;
