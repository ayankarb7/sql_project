-- Формулировка: На каждом этапе воронки продаж количество
-- объектов уменьшается, то есть не все объявления получают
-- просмотры, а просмотры не всегда приводят к сделкам.
--
-- Вывод: количество сделок значительно меньше количества
-- просмотров, это говорит о потерях на этапе принятия решения
-- клиентом.

WITH funnel AS (
    SELECT
        (SELECT count(*) FROM listings) AS total_listings,
        (SELECT count(*) FROM viewings) AS total_viewings,
        (SELECT count(*) FROM deals) AS total_deals
)
SELECT *
FROM funnel;
