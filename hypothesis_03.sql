-- Формулировка: Агенты с разным офисом показывают разную
-- эффективность по количеству объявлений и сделок.
--
-- Вывод: различие в активности и результативности офисов есть.
-- South Branch и Central показывают наибольшее количество как
-- объявлений, так и сделок, что указывает на их более высокую
-- общую эффективность. При этом соотношение между количеством
-- объявлений и сделок остаётся стабильным, что говорит о схожей
-- конверсии между офисами, несмотря на разный объём работы.

SELECT
    a.office,
    count(DISTINCT l.listing_id) AS total_listings,
    count(DISTINCT d.deal_id) AS total_deals
FROM agents a
LEFT JOIN listings l ON a.agent_id = l.agent_id
LEFT JOIN deals d ON l.listing_id = d.listing_id
GROUP BY a.office
ORDER BY total_deals DESC;
