-- Формулировка: Средняя стоимость объектов отличается в разных
-- городах.
--
-- Вывод: большой разницы не выявлено, но средняя стоимость
-- недвижимости всё же отличается в зависимости от города.
-- Это может быть связано с уровнем спроса, развитием инфраструктуры
-- и особенностями рынка.

SELECT
    city,
    avg(price) AS avg_price
FROM properties
WHERE city IN (
    SELECT DISTINCT city
    FROM properties
)
GROUP BY city
ORDER BY avg_price DESC;
