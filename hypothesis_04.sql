-- Формулировка: Некоторые агенты создают значительно больше
-- объявлений, чем другие.
--
-- Вывод: нагрузка между агентами распределена неравномерно.
-- Есть группа агентов, которые создают значительно больше
-- объявлений, чем остальные, что может говорить о различиях
-- в активности, опыте или уровне вовлечённости в работу.

SELECT
    a.agent_id,
    a.full_name,
    count(DISTINCT l.listing_id) AS total_listings
FROM agents a
LEFT JOIN listings l ON a.agent_id = l.agent_id
GROUP BY a.agent_id, a.full_name
ORDER BY total_listings DESC;
