-- Формулировка: Не все объявления переходят в сделку.
--
-- Вывод: часть объявлений остаётся без сделок. Такие объекты
-- требуют дополнительного анализа, чтобы определить, почему
-- отсутствует продажа.

SELECT
    l.listing_id,
    l.status
FROM listings l
LEFT JOIN deals d ON l.listing_id = d.listing_id
WHERE d.deal_id IS NULL
ORDER BY l.listing_id;
