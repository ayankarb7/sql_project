-- Формулировка: Самые новые объекты недвижимости могут иметь
-- более высокую стоимость.
--
-- Вывод: среди самых новых объектов (2024 года постройки)
-- стоимость значительно различается. Это говорит о том, что
-- сам по себе год постройки не определяет цену объекта. На
-- стоимость, вероятно, также влияют город, площадь, тип
-- недвижимости и другие характеристики.

SELECT
    property_id,
    city,
    build_year,
    price
FROM properties
WHERE build_year IS NOT NULL
ORDER BY build_year DESC
LIMIT 10;
