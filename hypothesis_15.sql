-- Формулировка: Некоторые агенты не заключили ни одной сделки.
--
-- Вывод: под это условие попал только один агент (id 32).
-- Вероятно, это связано с низкой активностью или недостатком
-- опыта.

SELECT
    a.agent_id,
    a.full_name
FROM agents a
WHERE a.agent_id NOT IN (
    SELECT DISTINCT l.agent_id
    FROM listings l
    JOIN deals d ON l.listing_id = d.listing_id
)
ORDER BY a.agent_id;
